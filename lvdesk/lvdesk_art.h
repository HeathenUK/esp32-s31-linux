/*
 * Generated artwork, kept as C arrays on purpose.
 *
 * All of it is `const`, so it lives in .rodata - the XIP image in flash, at
 * zero RSS. Measured this session, reading and executing from XIP costs about
 * 1.5% against RAM, so artwork here is close to free, where bitmaps loaded at
 * runtime would cost real memory on a board with ~3.9 MB available.
 *
 * The window controls are drawn rather than taken from the font because LVGL's
 * built-in symbol set has no maximise, restore or minimise glyph - the first
 * version used LV_SYMBOL_COPY for maximise, which is two overlapping pages and
 * means nothing. A minus bar, a square, and two offset squares are what every
 * desktop uses and what people already read without thinking.
 *
 * The desk background is a 16x16 *tile*, not a full-screen image: an 800x480
 * RGB565 wallpaper is 768,000 bytes - a fifth of the free RAM - and would also
 * enlarge every repaint that uncovers desk. LVGL repeats this one itself.
 */
